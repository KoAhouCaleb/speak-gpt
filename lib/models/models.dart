/// A named set of token biases sent as `logit_bias`.
class LogitBiasSet {
  LogitBiasSet({required this.id, required this.name, Map<String, int>? biases})
    : biases = biases ?? {};

  final String id;
  String name;

  /// Token id -> bias in the range -100..100.
  final Map<String, int> biases;

  Map<String, dynamic> toJson() => {'id': id, 'name': name, 'biases': biases};

  factory LogitBiasSet.fromJson(Map<String, dynamic> json) => LogitBiasSet(
    id: '${json['id']}',
    name: '${json['name'] ?? ''}',
    biases: {
      for (final e in (json['biases'] as Map? ?? {}).entries)
        '${e.key}': (e.value as num).toInt(),
    },
  );
}

